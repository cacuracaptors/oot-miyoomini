def c_str(s, enc="cp932"):
    b = s.encode(enc)
    out = '"'
    for ch in b:
        if ch == 0x22 or ch == 0x5C:
            out += "\\" + chr(ch)
        elif 32 <= ch < 127:
            out += chr(ch)
        else:
            out += "\\x%02X\"\"" % ch
    return out + '"'


